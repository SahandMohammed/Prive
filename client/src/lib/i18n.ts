const savedLanguage = (localStorage.getItem('prive_language') as 'en' | 'ckb') || 'en'

// Apply initial document direction and language attributes
if (typeof document !== 'undefined') {
  document.documentElement.lang = savedLanguage
  document.documentElement.dir = savedLanguage === 'ckb' ? 'rtl' : 'ltr'
}

i18n.use(initReactI18next).init({
  resources,
  lng: savedLanguage,
  fallbackLng: 'en',
  interpolation: {
    escapeValue: false,
  },
})

export function changeAppLanguage(lang: 'en' | 'ckb') {
  i18n.changeLanguage(lang)
  localStorage.setItem('prive_language', lang)
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'ckb' ? 'rtl' : 'ltr'
  }
}

export default i18n
